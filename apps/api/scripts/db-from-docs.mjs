// Generates the initial database artifacts in apps/api/prisma from the validated blocks in docs/database.md
// (the same blocks tools/doc-validation proves on PostgreSQL 16/18):
//   schema.prisma                                    ← <!-- validate:schema.prisma -->
//   migrations/0001_init/migration.sql               ← `prisma migrate diff --from-empty` of that schema
//   migrations/0002_constraints_search_integrity/…   ← <!-- validate:0002.sql --> (verbatim)
//   migrations/0003_money_stock_functions/…          ← <!-- validate:0003.sql --> (verbatim)
//   migrations/0008_dispatch_order/…                 ← <!-- validate:0008.sql --> (verbatim; task 5.2, §8.4)
//   migrations/0009_cancel_order/…                   ← <!-- validate:0009.sql --> (verbatim; task 5.3, §8.3a)
//
//   node scripts/db-from-docs.mjs          write the files
//   node scripts/db-from-docs.mjs --check  exit 1 if any file differs (CI drift guard)
//
// Later schema changes are new migrations (0004+), never edits to these. A later migration whose SQL the doc owns
// (so tools/doc-validation proves it) is listed in DOC_MIGRATIONS and generated the same way.
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const API = join(dirname(fileURLToPath(import.meta.url)), '..');
const DOC = join(API, '..', '..', 'docs', 'database.md');

export const MIGRATIONS = ['0001_init', '0002_constraints_search_integrity', '0003_money_stock_functions'];
/** Later migrations generated from a validated doc block: block → [directory, doc section]. */
export const DOC_MIGRATIONS = { '0008.sql': ['0008_dispatch_order', '§8.4'], '0009.sql': ['0009_cancel_order', '§8.3a'] };
const SCHEMA_HEADER = '// GENERATED from docs/database.md §5 by scripts/db-from-docs.mjs. Edit the doc, then regenerate.\n';
const SQL_HEADER = (section) => `-- GENERATED from docs/database.md ${section} by scripts/db-from-docs.mjs. Do not edit.\n`;

/** Returns the validated fenced blocks keyed by marker name. Throws if a required block is missing or duplicated. */
export function extractBlocks(md) {
  const re = /<!-- validate:([\w.-]+) -->\s*\n```(\w+)\n([\s\S]*?)```/g;
  const out = {};
  for (const m of md.matchAll(re)) {
    if (out[m[1]] !== undefined) throw new Error(`docs/database.md: duplicate <!-- validate:${m[1]} --> block`);
    out[m[1]] = m[3];
  }
  for (const k of ['schema.prisma', '0002.sql', '0003.sql']) {
    if (out[k] === undefined) throw new Error(`docs/database.md: missing <!-- validate:${k} --> block`);
  }
  return out;
}

function prismaBin() {
  const require = createRequire(join(API, 'package.json'));
  return join(dirname(require.resolve('prisma/package.json')), 'build', 'index.js');
}

function initSql(schema) {
  const dir = mkdtempSync(join(tmpdir(), 'artq-schema-'));
  try {
    const file = join(dir, 'schema.prisma');
    writeFileSync(file, schema);
    const env = { ...process.env, DATABASE_URL: 'postgresql://x@localhost/x', PRISMA_HIDE_UPDATE_MESSAGE: '1' };
    return execFileSync(process.execPath, [prismaBin(), 'migrate', 'diff', '--from-empty', '--to-schema-datamodel', file, '--script'], { env }).toString();
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

/** Expected file contents (relative path → content) derived from the doc. */
export function expectedFiles(md = readFileSync(DOC, 'utf8')) {
  const b = extractBlocks(md);
  const schema = SCHEMA_HEADER + b['schema.prisma'];
  return {
    'prisma/schema.prisma': schema,
    'prisma/migrations/migration_lock.toml': '# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "postgresql"\n',
    [`prisma/migrations/${MIGRATIONS[0]}/migration.sql`]: SQL_HEADER('§5') + initSql(schema),
    [`prisma/migrations/${MIGRATIONS[1]}/migration.sql`]: SQL_HEADER('§6') + b['0002.sql'],
    [`prisma/migrations/${MIGRATIONS[2]}/migration.sql`]: SQL_HEADER('§6b') + b['0003.sql'],
    ...Object.fromEntries(Object.entries(DOC_MIGRATIONS).map(([key, [dir, section]]) => {
      if (b[key] === undefined) throw new Error(`docs/database.md: missing <!-- validate:${key} --> block`);
      return [`prisma/migrations/${dir}/migration.sql`, SQL_HEADER(section) + b[key]];
    })),
  };
}

/** Relative paths whose committed content differs from the doc (missing files count as drift). */
export function drift(root = API, files = expectedFiles()) {
  return Object.entries(files)
    .filter(([rel, content]) => !existsSync(join(root, rel)) || readFileSync(join(root, rel), 'utf8') !== content)
    .map(([rel]) => rel);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const files = expectedFiles();
  if (process.argv.includes('--check')) {
    const d = drift(API, files);
    if (d.length) {
      console.error(`Out of sync with docs/database.md (run: pnpm --filter @artq/api db:from-docs):\n  ${d.join('\n  ')}`);
      process.exit(1);
    }
    console.log('prisma schema and migrations match docs/database.md');
  } else {
    for (const [rel, content] of Object.entries(files)) {
      mkdirSync(dirname(join(API, rel)), { recursive: true });
      writeFileSync(join(API, rel), content);
      console.log('wrote', rel);
    }
  }
}
